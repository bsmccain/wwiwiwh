import { DEFAULT_INK_SET, INK_SETS, type Inks } from '../app/theme';

/** The custom properties an ink set changes. Everything else in tokens.css and app.css is mixed from these. */
export const INK_PROPERTIES: readonly (readonly [property: string, ink: keyof Inks])[] = [
  ['--sheet', 'sheet'],
  ['--key', 'key'],
  ['--key-2', 'key2'],
  ['--home', 'home'],
  ['--away', 'away'],
  ['--away-deep', 'awayDeep'],
  ['--home-on-key', 'homeOnKey'],
  ['--away-on-key', 'awayOnKey'],
];

function rule(selector: string, inks: Inks): string {
  const lines = INK_PROPERTIES.map(([property, ink]) => `  ${property}: ${inks[ink].toLowerCase()};`);
  return `${selector} {\n${lines.join('\n')}\n}\n`;
}

/**
 * The text of src/styles/ink-sets.css: the inks of every set but Classic as custom properties.
 * A set's light printing matches on the set alone and its dark printing on the set and the theme
 * together, so the dark one wins over both the light one and Classic's own dark rules.
 */
export function inkSetsCss(): string {
  const head = [
    '/*',
    ' * Generated from src/app/theme.ts: the inks of every set but Classic, whose colours are the defaults in',
    ' * tokens.css and app.css. Do not edit this file. Change the inks in theme.ts and run `npm run inks`.',
    ' */',
  ].join('\n');
  const rules = INK_SETS.filter((set) => set.id !== DEFAULT_INK_SET).flatMap((set) => {
    const selector = `:root[data-inks='${set.id}']`;
    return [rule(selector, set.light), rule(`${selector}[data-theme='dark']`, set.dark)];
  });
  return `${head}\n${rules.join('\n')}`;
}
